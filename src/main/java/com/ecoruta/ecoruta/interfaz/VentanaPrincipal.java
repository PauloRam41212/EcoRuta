    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
         String origen = txtOrigen.getText().trim();
    String destino = txtDestino.getText().trim();
    String transporte = cmbTransporte.getSelectedItem().toString();

    if (origen.isEmpty() || destino.isEmpty() || txtDistancia.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Completa todos los campos.");
        return;
    }

    try {
        double distancia = Double.parseDouble(txtDistancia.getText().trim());

        if (distancia <= 0) {
            JOptionPane.showMessageDialog(this,
                    "La distancia debe ser mayor que cero.");
            return;
        }

        // Factores estimados de emisiones en kg de CO2 por km
        double factor;

        switch (transporte.trim().toLowerCase()) {
    case "bicicleta":
    case "caminando":
        factor = 0.0;
        break;

    case "transporte público":
    case "transporte publico":
        factor = 0.08;
        break;

    case "automóvil":
    case "automovil":
        factor = 0.192;
        break;

    default:
        factor = 0.0;
        break;
}

        double emisiones = distancia * factor;

        String sql = """
            INSERT INTO rutas
            (origen, destino, distancia, transporte, emisiones, fecha)
            VALUES (?, ?, ?, ?, ?, ?)
        """;

        try (Connection conexion = ConexionBD.conectar();
             PreparedStatement pst = conexion.prepareStatement(sql)) {

            pst.setString(1, origen);
            pst.setString(2, destino);
            pst.setDouble(3, distancia);
            pst.setString(4, transporte);
            pst.setDouble(5, emisiones);
            pst.setString(6, LocalDate.now().toString());

            pst.executeUpdate();
        }

        JOptionPane.showMessageDialog(this,
                "¡Ruta registrada correctamente!\n\n"
                + "Origen: " + origen
                + "\nDestino: " + destino
                + "\nDistancia: " + distancia + " km"
                + "\nTransporte: " + transporte
                + "\nEmisiones estimadas: " + String.format("%.3f", emisiones) + " kg CO2");

        txtOrigen.setText("");
        txtDestino.setText("");
        txtDistancia.setText("");

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Ingresa una distancia válida en kilómetros.");
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error al guardar la ruta: " + e.getMessage());
    }
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnHistorialActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHistorialActionPerformed


    String sql = "SELECT * FROM rutas ORDER BY id DESC";

    DefaultTableModel modelo = new DefaultTableModel();

    modelo.addColumn("ID");
    modelo.addColumn("Origen");
    modelo.addColumn("Destino");
    modelo.addColumn("Distancia (km)");
    modelo.addColumn("Transporte");
    modelo.addColumn("CO2 (kg)");
    modelo.addColumn("Fecha");

    try (Connection conexion = ConexionBD.conectar();
         PreparedStatement pst = conexion.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        double totalCO2 = 0;

        while (rs.next()) {

            Object[] fila = {
                rs.getInt("id"),
                rs.getString("origen"),
                rs.getString("destino"),
                rs.getDouble("distancia"),
                rs.getString("transporte"),
                rs.getDouble("emisiones"),
                rs.getString("fecha")
            };

            modelo.addRow(fila);
            totalCO2 += rs.getDouble("emisiones");
        }

        JTable tabla = new JTable(modelo);
        JScrollPane scroll = new JScrollPane(tabla);

        JOptionPane.showMessageDialog(
                this,
                new Object[]{
                    "HISTORIAL DE RECORRIDOS",
                    scroll,
                    "Emisiones acumuladas: "
                    + String.format("%.3f", totalCO2) + " kg CO2"
                },
                "EcoRuta - Historial",
                JOptionPane.INFORMATION_MESSAGE
        );

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(this,
                "Error al consultar el historial: " + e.getMessage());
    }

    }//GEN-LAST:event_btnHistorialActionPerformed

